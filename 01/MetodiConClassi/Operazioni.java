package MetodiConClassi;

public class Operazioni {
    static int somma(int n1, int n2){
        return n1 + n2;
    }

    static int sottrazione(int n1, int n2){
        return n1 - n2;
    }

    static double divisione(int n1, int n2){
        return (double) n1/n2;
    }

    static int prodotto(int n1, int n2){
        return n1 * n2;
    }
}
